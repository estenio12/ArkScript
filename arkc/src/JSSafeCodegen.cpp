    std::string JSSafeCodegen::Transpile(const Module& module)
    {
        js_buffer.clear();
        js_buffer.reserve(65536);

        EmitHeader(module.name);

        // 1. Transpila as declarações de dados readonly (RData) globais
        if (!module.rdata_decls.empty()) {
            js_buffer.append("// --- Global Readonly Data (rdata) ---\n");
            for (const auto& rdata : module.rdata_decls) {
                compile_stack.clear();
                ProcessInstructions(rdata.body);
                
                // O topo da pilha de compilação contém a expressão resolvida
                std::string init_expr = compile_stack.empty() ? "null" : compile_stack.back();
                
                // Módulos ES6: rdata públicos são exportados como const do JS
                if (rdata.visibility == "public") {
                    std::format_to(std::back_inserter(js_buffer), "export const {} = {};\n", rdata.name, init_expr);
                } else {
                    std::format_to(std::back_inserter(js_buffer), "const {} = {};\n", rdata.name, init_expr);
                }
            }
            js_buffer.append("\n");
        }

        // 2. Transpila as Funções do Módulo
        js_buffer.append("// --- Module Functions ---\n");
        for (const auto& func : module.functions) {
            compile_stack.clear();
            
            // Monta a assinatura dos parâmetros da função JS
            std::string params_str;
            for (size_t i = 0; i < func.params.size(); ++i) {
                params_str += func.params[i].name;
                if (i + 1 < func.params.size()) params_str += ", ";
            }

            // Exporta a função se a visibilidade da ArkScript for pública
            if (func.visibility == "public") {
                std::format_to(std::back_inserter(js_buffer), "export function {}({}) {{\n", func.name, params_str);
            } else {
                std::format_to(std::back_inserter(js_buffer), "function {}({}) {{\n", func.name, params_str);
            }

            // Processa as instruções do corpo na fita linear
            ProcessInstructions(func.body);

            js_buffer.append("}\n\n");
        }

        return std::move(js_buffer);
    }

    void JSSafeCodegen::EmitHeader(const std::string& module_name)
    {
        std::format_to(std::back_inserter(js_buffer), 
            "// ==========================================================================\n"
            "//  JSSafe generated by ArkScript \n"
            "//  Module: {}\n"
            "//  Target: ECMAScript ES6+ Modules\n"
            "// ==========================================================================\n\n", 
            module_name
        );
    }

    void JSSafeCodegen::ProcessInstructions(const std::vector<Instruction>& instructions)
    {
        for (const auto& inst : instructions) {
            std::visit([this](auto&& arg) {
                using T = std::decay_t<decltype(arg)>;

                // --- Operações de Empilhamento de Contexto ---
                if constexpr (std::is_same_v<T, Push>) {
                    compile_stack.push_back(ResolveLiteral(arg.value));
                }
                else if constexpr (std::is_same_v<T, Load>) {
                    compile_stack.push_back(arg.name);
                }

                // --- Reconstrução Matemática de Expressões ---
                else if constexpr (std::is_same_v<T, Add> || std::is_same_v<T, Sub> || 
                                   std::is_same_v<T, Mul> || std::is_same_v<T, Div>) {
                    if (compile_stack.size() < 2) {
                        throw std::runtime_error("Erro de Transpilação: Elementos insuficientes na pilha de compilação.");
                    }
                    std::string right = compile_stack.back(); compile_stack.pop_back();
                    std::string left = compile_stack.back(); compile_stack.pop_back();
                    
                    char op = '+';
                    if constexpr (std::is_same_v<T, Sub>) op = '-';
                    else if constexpr (std::is_same_v<T, Mul>) op = '*';
                    else if constexpr (std::is_same_v<T, Div>) op = '/';

                    // Envelopa com parênteses para garantir precedência matemática estrita do IR
                    compile_stack.push_back(std::format("({} {} {})", left, op, right));
                }

                // --- Declaração de Variáveis e Atribuições Estruturadas ---
                else if constexpr (std::is_same_v<T, DclVar> || std::is_same_v<T, DclConst>) {
                    // JavaScript moderno: usa 'let' ou 'const'. 
                    // Como ArkScript inicializa com default, definimos um placeholder de segurança se o desenvolvedor esquecer.
                    std::string keyword = std::is_same_v<T, DclConst> ? "const" : "let";
                    std::format_to(std::back_inserter(js_buffer), "    {} {};\n", keyword, arg.name);
                }
                else if constexpr (std::is_same_v<T, Store>) {
                    if (!compile_stack.empty()) {
                        std::string expr = compile_stack.back(); compile_stack.pop_back();
                        std::format_to(std::back_inserter(js_buffer), "    {} = {};\n", arg.name, expr);
                    }
                }
                else if constexpr (std::is_same_v<T, Assign>) {
                    // Atribuição direta. O valor correto já terá sido jogado no Store subsequente da fita.
                    // Esta instrução funciona como uma flag sintática no nosso modelo de fita linear.
                }

                // --- Controle de Fluxo: Retornos e Chamadas ---
                else if constexpr (std::is_same_v<T, Ret>) {
                    if (!compile_stack.empty()) {
                        std::string expr = compile_stack.back(); compile_stack.pop_back();
                        std::format_to(std::back_inserter(js_buffer), "    return {};\n", expr);
                    } else {
                        js_buffer.append("    return;\n");
                    }
                }
                else if constexpr (std::is_same_v<T, CallFunc>) {
                    // Coleta os argumentos resolvidos da pilha com base no 'count' da função
                    std::vector<std::string> args(arg.count);
                    for (int i = arg.count - 1; i >= 0; --i) {
                        args[i] = compile_stack.back();
                        compile_stack.pop_back();
                    }

                    std::string args_str;
                    for (size_t i = 0; i < args.size(); ++i) {
                        args_str += args[i];
                        if (i + 1 < args.size()) args_str += ", ";
                    }

                    // A chamada gera uma expressão JS que pode ser aninhada ou disparada diretamente
                    std::string call_expr = std::format("{}({})", arg.name, args_str);
                    compile_stack.push_back(call_expr);
                    
                    // Se a chamada for usada como um comando solto (CallStmtNode), descarrega direto no buffer
                    // Detectável se a pilha não for consumida por um Store/Ret subsequente.
                    // Para simplificar, deixamos a expressão na pilha para o próximo comando tratá-la.
                }
                else if constexpr (std::is_same_v<T, Pop> || std::is_same_v<T, Conv>) {
                    // Operações puras de otimização de tipo/limpeza de pilha interna da VM.
                    // No JS estruturado e dinâmico, elas se tornam totalmente redundantes e são ignoradas!
                }

            }, inst);
        }

        // Se sobrar alguma expressão órfã de função na pilha que não foi consumida por um Ret ou Store, emite como comando
        while (!compile_stack.empty()) {
            std::format_to(std::back_inserter(js_buffer), "    {};\n", compile_stack.back());
            compile_stack.pop_back();
        }
    }

    std::string JSSafeCodegen::ResolveLiteral(const LiteralValue& value)
    {
        return std::visit([](auto&& val) -> std::string {
            using L = std::decay_t<decltype(val)>;
            if constexpr (std::is_same_v<L, std::string>) {
                return std::format("\"{}\"", val); // Strings ganham aspas duplas no JS
            }
            else if constexpr (std::is_same_v<L, char>) {
                return std::format("'{}'", val);
            }
            else {
                return std::format("{}", val); // Ints e Floats saem normais
            }
        }, value);
    }
